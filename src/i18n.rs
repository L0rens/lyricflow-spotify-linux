pub fn language_name(code: &str) -> &'static str {
    LANGUAGES
        .iter()
        .find(|(id, _)| *id == code)
        .map(|(_, name)| *name)
        .unwrap_or("English")
}
pub fn next_language(code: &str, direction: i64) -> &'static str {
    let index = LANGUAGES
        .iter()
        .position(|(id, _)| *id == code)
        .unwrap_or(0) as i64;
    LANGUAGES[(index + direction).rem_euclid(LANGUAGES.len() as i64) as usize].0
}
